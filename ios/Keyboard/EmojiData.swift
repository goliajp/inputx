/// Categorized emoji catalog for the Inputx emoji picker (item 90).
///
/// Modeled on iOS 18 system emoji keyboard's category structure: a "recent"
/// section followed by 8 stable category buckets. Per-category emoji ordering
/// roughly mirrors the system keyboard (most-iconic-first within each bucket)
/// but isn't required to match exactly — the user-perceived freshness signal
/// is "the categories are the standard ones and tapping a tab jumps to a
/// non-empty section."
///
/// Scope note: this v1 ships a curated ~1000-emoji subset covering everyday
/// usage. Skin-tone variants and complex ZWJ sequences (family permutations,
/// professional combinations) are deliberately excluded — the long-press
/// skin-tone selector + ZWJ search are v3 work.
struct EmojiCategory {
    /// Section header label (debug / VoiceOver). Not displayed in the bar.
    let name: String
    /// Glyph drawn into the tab strip. SF Symbol name OR an emoji codepoint
    /// string; the renderer decides which based on whether the value is a
    /// valid SF Symbol.
    let tabIcon: String
    /// `true` if `tabIcon` is an SF Symbol; `false` if it's an emoji glyph.
    /// Cleaner than glyph-vs-symbol heuristics at render time.
    let tabIconIsSymbol: Bool
    let emojis: [String]
}

