/// Persistent recent-emojis store, backed by the App Group UserDefaults so
/// the main app + keyboard extension see the same list (item 90 — recent).
enum RecentEmojis {
    private static let key = "inputx_recent_emojis"
    /// Cap at 30 — matches iOS system keyboard's visible recent row size,
    /// keeps churn-rate sane (one tap doesn't push 15+ favorites off).
    private static let cap = 30

    static func load() -> [String] {
        return inputxSharedDefaults?.stringArray(forKey: key) ?? []
    }

    /// Record use of `emoji`: prepend to the list, de-dup (last-use wins),
    /// truncate to `cap`. Idempotent on a freshly-used emoji.
    static func record(_ emoji: String) {
        var current = load()
        current.removeAll { $0 == emoji }
        current.insert(emoji, at: 0)
        if current.count > cap { current = Array(current.prefix(cap)) }
        inputxSharedDefaults?.set(current, forKey: key)
    }

    static func clear() {
        inputxSharedDefaults?.removeObject(forKey: key)
    }
}
