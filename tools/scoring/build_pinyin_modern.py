def main() -> int:
    rows: list[tuple[str, str, int]] = []
    seen: set[tuple[str, str]] = set()

    for cat, items in CATEGORIES.items():
        for word, freq in items:
            # pypinyin lazy_pinyin: 词 → list of syllables (no tones).
            # Handle words with non-CJK chars (e.g. "B轮", "up主", "HIIT")
            # gracefully — pypinyin keeps them as-is.
            try:
                syllables = lazy_pinyin(word)
            except Exception as e:
                print(f"warning: pypinyin failed for {word!r}: {e}")
                continue
            pinyin = "".join(syllables).lower()
            # Reject pinyin that contains non-letter chars (incl. digits
            # from "B轮" etc.) — those don't index cleanly under the FST.
            if not pinyin.isalpha() or not pinyin.isascii():
                # Strip non-letter chars and retry; if still non-ascii or
                # empty, skip the entry.
                pinyin = "".join(c for c in pinyin if c.isascii() and c.isalpha())
                if not pinyin:
                    continue
            key = (pinyin, word)
            if key in seen:
                continue
            seen.add(key)
            rows.append((pinyin, word, freq))

    rows.sort(key=lambda r: (-r[2], r[0], r[1]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w") as f:
        f.write("# Pinyin modern vocab supplement — generated by tools/scoring/build_pinyin_modern.py\n")
        f.write("# format: pinyin\\tword\\tfreq.  Consumed by pinyin-build-fst as overlay.\n")
        for py, w, freq in rows:
            f.write(f"{py}\t{w}\t{freq}\n")
    print(f"wrote {OUT} ({len(rows)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
